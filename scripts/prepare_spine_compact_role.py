"""Fit hero_001 to the current 320x320 Home viewport without changing firmware.

Requires bounds generated by tools/spine_role_layout.cpp. The existing 512 atlas
and texture are reused byte-for-byte; only setup root translation, the wait
animation name, and role.json's load scale change. Original files are untouched.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import math
import shutil
import struct
import sys
from pathlib import Path

class BinaryHeader:
    def __init__(self, data: bytearray):
        self.data, self.pos = data, 8
    def varint(self):
        value = shift = 0
        for _ in range(5):
            b = self.data[self.pos]; self.pos += 1
            value |= (b & 127) << shift
            if b < 128: return value
            shift += 7
        raise ValueError("invalid Spine varint")
    def string(self):
        n = self.varint()
        if n <= 1: return ""
        value = bytes(self.data[self.pos:self.pos+n-1]).decode("utf-8")
        self.pos += n-1
        return value
    def float(self):
        value = struct.unpack_from(">f", self.data, self.pos)[0]
        self.pos += 4
        return value
    def boolean(self):
        value = self.data[self.pos]; self.pos += 1
        if value not in (0, 1): raise ValueError("invalid boolean")
        return bool(value)
    def root(self):
        version = self.string()
        if not version.startswith("4.2."): raise ValueError(version)
        header = [self.float() for _ in range(5)]
        nonessential = self.boolean()
        if nonessential:
            self.float(); self.string(); self.string()
        for _ in range(self.varint()): self.string()
        bones = self.varint()
        name = self.string()
        self.float()  # rotation; the root has no parent varint
        x_offset = self.pos
        x, y = self.float(), self.float()
        return dict(runtime=version, skeleton_header=header, bones=bones,
                    name=name, x=x, y=y, x_offset=x_offset, y_offset=x_offset+4)

def main():
    p = argparse.ArgumentParser()
    p.add_argument("--source", type=Path, required=True)
    p.add_argument("--bounds", type=Path, required=True)
    p.add_argument("--output", type=Path, required=True)
    p.add_argument("--max-width", type=float, default=224)
    p.add_argument("--max-height", type=float, default=260)
    p.add_argument("--center-y", type=float, default=158)
    a = p.parse_args()
    bounds = json.loads(a.bounds.read_text(encoding="utf-8"))
    if bounds["scale"] != 1: raise ValueError("bounds must use scale=1")
    x1,y1,x2,y2 = bounds["bounds"]
    # Four percent geometric margin for unsampled extrema and raster rounding.
    scale = min(a.max_width/(x2-x1),a.max_height/(y2-y1))*0.96
    root_dx = -(x1+x2)/2
    root_dy = (320-a.center_y)/scale-(y1+y2)/2
    if not all(math.isfinite(v) for v in (scale,root_dx,root_dy)): raise ValueError("invalid fit")
    a.output.mkdir(parents=True,exist_ok=True)
    skel = bytearray((a.source/"skeleton.skel").read_bytes())
    root = BinaryHeader(skel).root()
    if root["bones"] != bounds["bones"]: raise ValueError("bone count mismatch")
    struct.pack_into(">f",skel,root["x_offset"],root["x"]+root_dx)
    struct.pack_into(">f",skel,root["y_offset"],root["y"]+root_dy)
    animation_names = [m["name"] for m in bounds["animations"]]
    rename_offset = None
    if "idle" not in animation_names:
        if "wait" not in animation_names: raise ValueError("no idle or wait")
        marker = bytes([5])+b"wait"
        if skel.count(marker) != 1: raise ValueError("ambiguous wait name; refusing byte patch")
        rename_offset = skel.index(marker)+1
        skel[rename_offset:rename_offset+4] = b"idle"
        animation_names = ["idle" if n=="wait" else n for n in animation_names]
    (a.output/"skeleton.skel").write_bytes(skel)
    for name in ("skeleton.atlas","texture.png"):
        shutil.copyfile(a.source/name,a.output/name)
    shifted = [(x1+root_dx)*scale+160,320-(y2+root_dy)*scale,
               (x2+root_dx)*scale+160,320-(y1+root_dy)*scale]
    report = dict(source=str(a.source.resolve()), runtime=root["runtime"],
                  target_screen=[320,320], node_position=[160,0],
                  scale=scale, original_bounds=[x1,y1,x2,y2],
                  expected_screen_bounds=shifted,
                  expected_region_pixels=math.ceil(shifted[2]-shifted[0])*math.ceil(shifted[3]-shifted[1]),
                  safety_margin=0.04,root_before=root,root_translation=[root_dx,root_dy],
                  rename_wait_offset=rename_offset,animations=animation_names,
                  skeleton_sha256=hashlib.sha256(skel).hexdigest())
    (a.output.parent/"layout.json").write_text(json.dumps(report,ensure_ascii=False,indent=2)+"\n",encoding="utf-8")
    print(json.dumps(report,ensure_ascii=False,indent=2))

if __name__ == "__main__":
    main()
